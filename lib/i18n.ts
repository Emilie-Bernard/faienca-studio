export const LOCALES = ['fr', 'en', 'es'] as const;
export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = 'fr';
export const LOCALE_COOKIE = 'faienca-lang';
export const LOCALE_NAMES: Record<Locale, string> = { fr: 'Français', en: 'English', es: 'Español' };
const DATE_LOCALES: Record<Locale, string> = { fr: 'fr-FR', en: 'en-GB', es: 'es-ES' };

export const isLocale = (value: unknown): value is Locale => typeof value === 'string' && (LOCALES as readonly string[]).includes(value);

/**
 * Langue choisie (cookie), sinon la première langue prise en charge du navigateur.
 * Sans en-tête : français. Navigateur dans une autre langue : anglais.
 */
export function pickLocale(cookie: string | null | undefined, acceptLanguage: string | null | undefined): Locale {
    if (isLocale(cookie)) return cookie;
    if (!acceptLanguage?.trim()) return DEFAULT_LOCALE;
    const wanted = acceptLanguage.split(',')
        .map((part, i) => { const [tag = '', ...params] = part.trim().split(';'); const q = params.map(p => p.trim()).find(p => p.startsWith('q=')); return { lang: tag.trim().toLowerCase().split('-')[0]!, q: q ? Number(q.slice(2)) : 1, i }; })
        .filter(l => l.lang && l.q > 0)
        .sort((a, b) => b.q - a.q || a.i - b.i);
    return wanted.find(l => isLocale(l.lang))?.lang as Locale | undefined ?? 'en';
}

export const formatDate = (t: number, locale: Locale) => new Date(t).toLocaleDateString(DATE_LOCALES[locale], { day: 'numeric', month: 'long', year: 'numeric' });

